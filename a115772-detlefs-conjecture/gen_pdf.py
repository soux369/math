#!/usr/bin/env python3
"""Generate proof.html (with the 24-pair table computed by our own BFS)
and render proof.pdf via WeasyPrint."""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("v", os.path.join(HERE, "verify.py"))
v = importlib.util.module_from_spec(spec)
spec.loader.exec_module(v)

seen, trans = v.bfs_pairs()


def fmt_S(S):
    if not S:
        return "∅"
    return "{" + ", ".join(f"{b0}{b1}" for (b0, b1) in sorted(S)) + "}"


def fmt_pair(p):
    (c, m), S = p
    return f"(({c}, {m}), {fmt_S(S)})"


rows = []
start = ((0, 0), frozenset({(0, 0)}))
ordered = [start] + sorted(seen - {start}, key=lambda p: (p[0][0], p[0][1], sorted(p[1])))
for idx, p in enumerate(ordered):
    (c, m), S = p
    outs = trans[p]
    if outs is None:
        t0 = t1 = "⊥"
    else:
        t0, t1 = fmt_pair(outs[0]), fmt_pair(outs[1])
    rows.append(
        f"<tr><td>p{idx}</td><td>({c}, {m})</td><td>{fmt_S(S)}</td>"
        f"<td>{'✓' if c % 2 == m % 2 else '✗'}</td>"
        f"<td>{'✓' if c == m else '–'}</td><td>{'✓' if (0, 0) in S else '–'}</td>"
        f"<td>{t0}</td><td>{t1}</td></tr>"
    )
table = "\n".join(rows)

html = f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<style>
  @page {{ size: A4; margin: 22mm 20mm 20mm 20mm;
    @bottom-center {{ content: "A115772 ⊊ {{x OR 4x}} — proof note"; font-size: 8pt; color: #888; }} }}
  body {{ font-family: "DejaVu Serif", "Noto Serif CJK JP", serif; font-size: 10.5pt; line-height: 1.5; color: #111; }}
  h1 {{ font-size: 16pt; text-align: center; margin-bottom: 2mm; }}
  .subtitle {{ text-align: center; color: #444; font-size: 10pt; margin-bottom: 8mm; }}
  h2 {{ font-size: 12.5pt; margin-top: 7mm; border-bottom: 0.4pt solid #bbb; padding-bottom: 1mm; }}
  .theorem {{ border: 0.8pt solid #333; padding: 3mm 4mm; margin: 4mm 0; background: #fafafa; }}
  .mono {{ font-family: "DejaVu Sans Mono", monospace; font-size: 9pt; }}
  table {{ border-collapse: collapse; margin: 4mm auto; font-size: 8.2pt; }}
  th, td {{ border: 0.4pt solid #999; padding: 1mm 1.6mm; text-align: center; }}
  th {{ background: #eee; }}
  .small {{ font-size: 9pt; color: #333; }}
  .center {{ text-align: center; }}
</style></head><body>

<h1>A115772 ⊊ {{x OR 4x}}:<br>Detlefs's Conjecture on OEIS A115772 Is False</h1>
<div class="subtitle">Proof note — November 27, 2026<br>
Repository: github.com/soux369/a115772-detlefs-conjecture</div>

<div class="theorem">
<b>Theorem.</b> Let A115772 = {{ i : 13·i = C(21, i) }}, where C is carryless
(GF(2)[X]) multiplication (OEIS A048720). Then
<div class="center" style="margin:2mm 0;">A115772 ⊊ {{ x OR 4x : x ≥ 0 }}.</div>
The inclusion ⊆ holds, but the equality conjectured by Detlefs (2010) fails:
325 = 65 OR (4·65) satisfies 13·325 = 4225 ≠ 4097 = C(21, 325), so
325 ∉ A115772. The two sets agree below 325.
</div>

<h2>1&nbsp;&nbsp;Disproof of the equality</h2>
<p>Take x = 65 = 1000001<sub>2</sub>. Then 4x = 260 = 100000100<sub>2</sub> and
i = x OR 4x = 101000101<sub>2</sub> = 325. As integers,
13·325 = (2<sup>6</sup>+1)<sup>2</sup> = 2<sup>12</sup> + 2<sup>7</sup> + 1 = 4225,
since 325 = 5·(2<sup>6</sup>+1) and 13·5 = 2<sup>6</sup>+1. In GF(2)[X], with
21 = 1 + X<sup>2</sup> + X<sup>4</sup> and 325 = (1 + X<sup>2</sup>)(1 + X<sup>6</sup>),
the cross terms cancel:
C(21, 325) = (1 + X<sup>2</sup> + X<sup>4</sup>)(1 + X<sup>2</sup>)(1 + X<sup>6</sup>)
= (1 + X<sup>6</sup>)<sup>2</sup> = 1 + X<sup>12</sup> = 4097.
Hence 325 ∉ A115772. Direct computation shows the two sets coincide for all
i &lt; 325; the next counterexamples are 335, 365, 367, 485.</p>

<h2>2&nbsp;&nbsp;Proof of the inclusion</h2>
<p>For the equation use the suffix state equation E(c, m, i) ⟺ c + 13i = m ⊕ C(21, i),
with E(c, m, 0) ⟺ c = m. Splitting off the LSB b of i (13 and 21 are odd):
E(c, m, i) ⟺ (c ≡ m mod 2) ∧ E(δ<sub>eq</sub>((c,m), b), ⌊i/2⌋), where
δ<sub>eq</sub>((c,m), b) = (⌊(c + 13b)/2⌋, ⌊(m ⊕ 21b)/2⌋).
For the right-hand side, bit j of x OR 4x is x<sub>j</sub> ∨ x<sub>j−2</sub>; the subset
DFA over NFA states (x<sub>j−2</sub>, x<sub>j−1</sub>) has transition
δ<sub>DFA</sub>(S, b) = {{ (b₁, x<sub>j</sub>) : ∃b₀, (b₀, b₁) ∈ S ∧ (x<sub>j</sub> ∨ b₀) = b }}.
Running both machines in lockstep from ((0,0), {{00}}), exactly <b>24 pairs</b> are
reachable (16 with c ≡ m (mod 2), 8 boundary pairs with c ≢ m (mod 2)):</p>

<table>
<tr><th>ID</th><th>(c, m)</th><th>S</th><th>c≡m (2)</th><th>c=m</th><th>00∈S</th><th>x=0 →</th><th>x=1 →</th></tr>
{table}
</table>

<p class="small">(⊥: the equation's bit mismatches there regardless of the input bit.
Successors are shown as full pairs ((c′, m′), S′). This table was generated by an
independent BFS implementation, not copied from the Lean source.)</p>

<p>On all 24 pairs: <b>closure</b> — if c ≡ m (mod 2), both successors are again in
the table; and <b>terminal implication</b> — c = m implies 00 ∈ S. Binary induction
on i, reconstructing the witness x bit by bit through DFA predecessors, then gives:
every i with 13i = C(21, i) is of the form x OR 4x. ∎</p>

<h2>3&nbsp;&nbsp;Verification</h2>
<p>The result is formalized in Lean 4 (<span class="mono">A115772Detlefs.lean</span>,
pure Lean 4.36.0, no Mathlib) and compiles with no errors and no
<span class="mono">sorry</span>; <span class="mono">#print axioms</span> reports
[propext, Classical.choice, Quot.sound] for the inclusion and the strictness, and
[propext, Quot.sound] for the disproof. Independently, the 24-pair reachable set was
recomputed by BFS from the definitions (the source of the table above), the terminal
implication was checked on every pair, the counterexample and its minimality were
verified directly, and the inclusion was brute-force checked for all i &lt; 2<sup>20</sup>
with no violation.</p>

<p class="small">Provenance: the proof, counterexample search and formalization were
produced by an AI agent (Gemini 4 Neon, task mode) from a brief by MONO; the closure,
numeric checks and Lean compilation were independently reproduced by a second AI
agent (Muse).</p>

</body></html>"""

with open(os.path.join(HERE, "proof.html"), "w") as f:
    f.write(html)
from weasyprint import HTML
HTML(os.path.join(HERE, "proof.html")).write_pdf(os.path.join(HERE, "proof.pdf"))
print("proof.pdf rendered")
